#!/usr/bin/env python3
"""Builds the landing page (GitHub Pages) from site/, assets/theme.toml, the latest release and
CHANGELOG.md. Python standard library only.

    python3 site/build.py --release release.json --out _site

`release.json` is `gh release view --json tagName,publishedAt,url,assets`. A missing asset in the
release stops the build, so the old page with working links stays published.
"""
import argparse
import html
import json
import re
import shutil
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
LANGS = {"en": "", "ro": "ro/"}
NEWS_COUNT = 3
PLACEHOLDER = re.compile(r"\{\{\{\s*(\w+)\s*\}\}\}|\{\{\s*(\w+)\s*\}\}")
SECTION = re.compile(r"^## \[(?P<version>[^\]]+)\] — (?P<date>\d{4}-\d{2}-\d{2})$", re.M)

# Release files: key used in the page -> end of the name after `rigscope-<version>-`
# (SHA256SUMS.txt is the whole name).
ASSET_KINDS = {
    "linux-appimage": "linux-x86_64.AppImage",
    "linux-deb": "linux-x86_64.deb",
    "linux-tar": "linux-x86_64.tar.gz",
    "mac-dmg": "macos-universal.dmg",
    "sha256": "SHA256SUMS.txt",
}
# Not in every release (0.2.0 and earlier have none): the page then has no Windows row or button.
OPTIONAL_ASSET_KINDS = {
    "windows-exe": "windows-x86_64.exe",
}

# Page file -> source. Screenshots exist in English; the Romanian page uses the Romanian
# memory screenshot where there is one.
IMAGES = {
    "logo.png": ROOT / "assets/icon.png",
    "favicon.png": ROOT / "docs/assets/icon-32.png",
    "og.png": ROOT / "docs/assets/rigscope-og.png",
    **{
        f"{n}.png": ROOT / f"docs/assets/screenshot-{n}.png"
        for n in ("memory", "memory-ro", "cpu", "storage", "gpu", "network", "battery", "sensors")
    },
}
FONTS = ("NotoSans-Regular.ttf", "NotoSans-Bold.ttf")


def theme_css(theme):
    """CSS custom properties from assets/theme.toml: the only place colours come from."""
    return (
        "/* generated by site/build.py from assets/theme.toml: do not edit */\n"
        ":root {\n"
        f"  --accent: {theme['accent']};\n  --accent-press: {theme['accent_press']};\n"
        f"  --warn: {theme['warn']};\n  --on-accent: {theme['bg_light']};\n"
        f"  --bg: {theme['bg_light']};\n  --fg: {theme['fg_light']};\n}}\n"
        "@media (prefers-color-scheme: dark) {\n"
        f"  :root {{\n    --bg: {theme['bg_dark']};\n    --fg: {theme['fg_dark']};\n  }}\n}}\n"
    )


def changelog_sections(md, count):
    """First `count` versions of the changelog: version, date, body (Markdown)."""
    matches = list(SECTION.finditer(md))[:count]
    out = []
    for i, m in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(md)
        body = md[m.end():end]
        cut = re.search(r"^## |^\[[^\]]+\]: \S+$", body, re.M)
        if cut:
            body = body[:cut.start()]
        out.append({"version": m["version"], "date": m["date"], "body": body.strip()})
    return out


def inline(text):
    """`code`, **bold** and [text](url) on text that is escaped here."""
    out = []
    for part in re.split(r"(`[^`]*`)", text):
        if part.startswith("`") and part.endswith("`") and len(part) > 1:
            out.append(f"<code>{html.escape(part[1:-1], quote=False)}</code>")
            continue
        part = html.escape(part, quote=False)
        part = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", part)
        part = re.sub(
            r"\[([^\]]+)\]\(([^)\s]+)\)",
            lambda m: f'<a href="{html.escape(m[2])}">{m[1]}</a>',
            part,
        )
        out.append(part)
    return "".join(out)


def md_to_html(md):
    """The changelog's Markdown subset: ###, lists, paragraphs, code, bold, links."""
    blocks, items, para = [], None, []

    def flush_para():
        if para:
            blocks.append(f"<p>{inline(' '.join(para))}</p>")
            para.clear()

    def flush_list():
        nonlocal items
        if items is not None:
            blocks.append("<ul>" + "".join(f"<li>{inline(i)}</li>" for i in items) + "</ul>")
            items = None

    for line in md.splitlines():
        if line.startswith("### "):
            flush_para()
            flush_list()
            blocks.append(f"<h4>{inline(line[4:].strip())}</h4>")
        elif line.startswith("- "):
            flush_para()
            if items is None:
                items = []
            items.append(line[2:].strip())
        elif line.startswith("  ") and items:
            items[-1] += " " + line.strip()
        elif not line.strip():
            flush_para()
            flush_list()
        else:
            flush_list()
            para.append(line.strip())
    flush_para()
    flush_list()
    return "\n".join(blocks)


def release_assets(release):
    """Key -> {name, url, size}. A missing required file stops the build; optional ones are
    left out."""
    version = release["tagName"].removeprefix("v")
    by_name = {a["name"]: a for a in release["assets"]}
    assets = {}
    for kind, suffix in ASSET_KINDS.items():
        name = suffix if kind == "sha256" else f"rigscope-{version}-{suffix}"
        if name not in by_name:
            raise SystemExit(f"Release {release['tagName']} has no file {name}")
        a = by_name[name]
        assets[kind] = {"name": name, "url": a["url"], "size": a["size"]}
    for kind, suffix in OPTIONAL_ASSET_KINDS.items():
        a = by_name.get(f"rigscope-{version}-{suffix}")
        if a:
            assets[kind] = {"name": a["name"], "url": a["url"], "size": a["size"]}
    return assets


def format_size(n):
    return f"{n / 1024 / 1024:.1f} MB"


def format_date(iso, months, pattern):
    y, m, d = (int(x) for x in iso[:10].split("-"))
    return pattern.format(d=d, month=months[m - 1], y=y)


def version_key(v):
    return tuple(int(x) for x in re.findall(r"\d+", v.split("-")[0])[:3])


def news_html(md, t, released):
    """Latest versions from the changelog, without those not released yet (the changelog is
    written before the release)."""
    out = []
    sections = [s for s in changelog_sections(md, NEWS_COUNT + 5)
                if version_key(s["version"]) <= version_key(released)]
    for s in sections[:NEWS_COUNT]:
        date = format_date(s["date"], t["months"], t["date_format"])
        out.append(
            f'<article class="release"><div class="release-head"><h3>{html.escape(s["version"])}</h3>'
            f'<time datetime="{s["date"]}">{date}</time></div>\n'
            f'<div class="release-body">{md_to_html(s["body"])}</div></article>'
        )
    return "\n".join(out)


def render(template, values):
    """{{{ key }}} = raw HTML, {{ key }} = escaped text; a missing key is an error."""
    def sub(m):
        raw, escaped = m[1], m[2]
        value = values[raw or escaped]
        return value if raw else html.escape(value)
    return PLACEHOLDER.sub(sub, template)


def build(release, out):
    assets = release_assets(release)
    version = release["tagName"].removeprefix("v")
    theme = tomllib.loads((ROOT / "assets/theme.toml").read_text(encoding="utf-8"))
    template = (SITE / "template.html").read_text(encoding="utf-8")
    changelog = (ROOT / "CHANGELOG.md").read_text(encoding="utf-8")
    kind_urls = {"linux": assets["linux-appimage"]["url"], "mac": assets["mac-dmg"]["url"]}
    if "windows-exe" in assets:
        kind_urls["windows"] = assets["windows-exe"]["url"]
    kinds = json.dumps(kind_urls)
    for lang, path in LANGS.items():
        t = json.loads((SITE / "i18n" / f"{lang}.json").read_text(encoding="utf-8"))
        values = {k: v for k, v in t.items() if isinstance(v, str)}
        values.update({
            "root": "../" if path else "",
            "path": path,
            "home": "../" if path else "./",
            "ro_href": "./" if path else "ro/",
            "lang": lang,
            "shot_memory": "memory-ro" if lang == "ro" else "memory",
            "version": version,
            "date": format_date(release["publishedAt"], t["months"], t["date_format"]),
            "kinds_json": kinds,
            "windows_label_attr": (
                f'data-label-windows="{html.escape(t["btn_windows"])}"' if "windows-exe" in assets else ""
            ),
            "windows_row": (
                f'<tr><td><a href="{html.escape(assets["windows-exe"]["url"])}">'
                f'{html.escape(assets["windows-exe"]["name"])}</a></td>'
                f'<td>{html.escape(t["dl_windows"])}</td>'
                f'<td>{format_size(assets["windows-exe"]["size"])}</td></tr>'
                if "windows-exe" in assets else ""
            ),
            "news_html": news_html(changelog, t, version),
            "name": theme["name"],
        })
        for code in LANGS:
            values[f"current_{code}"] = 'aria-current="page"' if code == lang else ""
        for kind, a in assets.items():
            key = kind.replace("-", "_")
            values[f"url_{key}"] = a["url"]
            values[f"name_{key}"] = a["name"]
            values[f"size_{key}"] = format_size(a["size"])
        page = out / path / "index.html"
        page.parent.mkdir(parents=True, exist_ok=True)
        page.write_text(render(template, values), encoding="utf-8")

    (out / "assets").mkdir(parents=True, exist_ok=True)
    for f in (SITE / "assets").iterdir():
        shutil.copy2(f, out / "assets" / f.name)
    for name, src in IMAGES.items():
        shutil.copy2(src, out / "assets" / name)
    for font in FONTS:
        shutil.copy2(ROOT / "assets/fonts" / font, out / "assets" / font)
    (out / "assets" / "theme.css").write_text(theme_css(theme), encoding="utf-8")
    (out / ".nojekyll").write_text("")


def main():
    p = argparse.ArgumentParser(description="Build the landing page.")
    p.add_argument("--release", required=True, help="JSON from gh release view --json tagName,publishedAt,url,assets")
    p.add_argument("--out", required=True, help="folder the page is written to")
    args = p.parse_args()
    release = json.loads(Path(args.release).read_text(encoding="utf-8"))
    out = Path(args.out)
    if out.exists():
        shutil.rmtree(out)
    build(release, out)
    print(f"Done: {out}")


if __name__ == "__main__":
    main()
